const { chromium } = require('playwright')
const menu = async (pg, top, item) => {
  await pg.click(`text=${top}`, { force: true }); await pg.waitForTimeout(250)
  await pg.click(`text=${item}`, { force: true }); await pg.waitForTimeout(400)
}
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext({ viewport: { width: 1440, height: 860 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  await pg.goto('http://localhost:5431/test-studio.html')
  await pg.waitForTimeout(2500)
  await pg.screenshot({ path: 'tmp/new-empty.png' })
  await menu(pg, 'Fichier', 'Nouveau document…')
  await pg.screenshot({ path: 'tmp/new-docmodal.png' })
  await pg.click('button:has-text("Créer")'); await pg.waitForTimeout(800)
  await pg.screenshot({ path: 'tmp/new-created.png' })
  await menu(pg, 'Édition', 'Remplir…')
  await pg.screenshot({ path: 'tmp/new-fill.png' })
  await pg.click('button:has-text("OK")'); await pg.waitForTimeout(300)
  await menu(pg, 'Image', 'Taille de la zone de travail…')
  await pg.screenshot({ path: 'tmp/new-canvassize.png' })
  await pg.click('button:has-text("OK")'); await pg.waitForTimeout(400)
  await menu(pg, 'Sélection', 'Plage de couleurs…')
  await pg.waitForTimeout(500)
  await pg.screenshot({ path: 'tmp/new-colorrange.png' })
  const pv = pg.locator('canvas').last()
  const box = await pv.boundingBox()
  await pg.mouse.click(box.x + box.width / 2, box.y + box.height / 2)
  await pg.waitForTimeout(400)
  await pg.screenshot({ path: 'tmp/new-colorrange2.png' })
  await pg.click('button:has-text("OK")'); await pg.waitForTimeout(500)
  await pg.click('text=Dentaire'); await pg.waitForTimeout(400)
  await pg.screenshot({ path: 'tmp/new-dental.png' })
  await pg.click('button:has-text("Guides du sourire")'); await pg.waitForTimeout(300)
  await pg.click('button:has-text("11")'); await pg.waitForTimeout(200)
  const main = await pg.locator('canvas').first().boundingBox()
  await pg.mouse.click(main.x + main.width / 2, main.y + main.height / 2)
  await pg.waitForTimeout(500)
  await pg.screenshot({ path: 'tmp/new-fdi.png' })
  console.log('ERRORS:', errs.filter((e) => !e.includes('favicon') && !e.includes('supabase') && !e.includes('net::')))
  await b.close()
})().catch((e) => console.log('FAIL', e.message))
