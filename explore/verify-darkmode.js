const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext()).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  await pg.goto('http://127.0.0.1:5431/login')
  await pg.fill('input[type="email"]', '' + (process.env.DP_USER||'') + '')
  await pg.fill('input[type="password"]', '' + (process.env.DP_PASS||'') + '')
  await pg.click('button[type="submit"]')
  await pg.waitForTimeout(3000)
  await pg.click('[aria-label="Passer en mode sombre"]')
  await pg.waitForTimeout(400)
  await pg.screenshot({ path: 'shots/theme-dark.png' })
  console.log('theme =', await pg.evaluate(() => document.documentElement.dataset.theme))
  await pg.evaluate(() => localStorage.setItem('dentopic.acq.guide', '1'))
  await pg.goto('http://127.0.0.1:5431/acquisition'); await pg.waitForTimeout(1000)
  // fermer tout modal éventuellement ouvert
  await pg.mouse.click(10, 400); await pg.waitForTimeout(400)
  await pg.screenshot({ path: 'shots/theme-dark-acq.png' })
  await pg.click('text=Nouvelle acquisition'); await pg.waitForTimeout(500)
  await pg.screenshot({ path: 'shots/theme-dark-modal.png' })
  await pg.mouse.click(10, 10); await pg.waitForTimeout(300)
  await pg.click('[aria-label="Passer en mode clair"]')
  await pg.waitForTimeout(400)
  console.log('theme retour =', await pg.evaluate(() => document.documentElement.dataset.theme))
  await pg.click('[aria-label="Passer en mode sombre"]'); await pg.waitForTimeout(300)
  await pg.reload(); await pg.waitForTimeout(1200)
  console.log('persist apres reload =', await pg.evaluate(() => document.documentElement.dataset.theme))
  console.log('ERRORS:', errs.filter(e => !e.includes('favicon')))
  await b.close()
})().catch(e => console.log('FAIL', e.message))
