const { chromium } = require('playwright')
const fs = require('fs')
;(async () => {
  fs.writeFileSync('qr-test.png', Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==','base64'))
  const b = await chromium.launch()
  const pg = await (await b.newContext({ viewport: { width: 1440, height: 860 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  await pg.goto('http://127.0.0.1:5431/login')
  await pg.evaluate(() => localStorage.setItem('dentopic.acq.guide','1'))
  await pg.fill('input[type="email"]', '' + (process.env.DP_USER||'') + '')
  await pg.fill('input[type="password"]', '' + (process.env.DP_PASS||'') + '')
  await pg.click('button[type="submit"]')
  await pg.waitForTimeout(3500)
  await pg.goto('http://127.0.0.1:5431/acquisition'); await pg.waitForTimeout(1200)
  await pg.mouse.click(20, 800); await pg.waitForTimeout(300)
  await pg.click('text=DÉPART'); await pg.waitForTimeout(800)
  await pg.click('text=Application mobile'); await pg.waitForTimeout(1000)
  const url = await pg.evaluate(() => document.body.innerText.match(/http[^\s]*\/capture\/[0-9a-f-]{36}/)?.[0])
  console.log('QR url:', url)
  // onglet mobile (même storage → déjà connecté)
  const mob = await pg.context().newPage()
  await mob.setViewportSize({ width: 390, height: 760 })
  await mob.goto(url); await mob.waitForTimeout(2500)
  await mob.screenshot({ path: 'shots/qr-mobile-wait.png' })
  console.log('avant start:', await mob.evaluate(() => document.body.innerText.includes('attente') ? 'en attente ✓' : document.body.innerText.slice(0,100)))
  await pg.click('text=Démarrer la session de capture'); await pg.waitForTimeout(2000)
  await mob.waitForTimeout(4000)
  console.log('apres start:', await mob.evaluate(() => document.body.innerText.includes('Session active') || document.body.innerText.includes('Destination :') ? 'active ✓' : document.body.innerText.slice(0,120)))
  await mob.screenshot({ path: 'shots/qr-mobile-active.png' })
  await mob.locator('input[type=file]').first().setInputFiles('qr-test.png')
  await mob.waitForTimeout(3000)
  console.log('envoi:', await mob.evaluate(() => document.body.innerText.includes('envoyée') ? 'photo reçue ✓' : 'échec: ' + document.body.innerText.slice(0,120)))
  await mob.screenshot({ path: 'shots/qr-mobile-sent.png' })
  console.log('ERRORS:', errs.filter(e => !e.includes('favicon')))
  await b.close()
})().catch(e => console.log('FAIL', e.message))
