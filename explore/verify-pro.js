const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome' }).catch(() => chromium.launch())
  const pg = await (await b.newContext({ viewport: { width: 1400, height: 1000 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  await pg.goto('http://localhost:5175/', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  if (await pg.locator('input[type="email"]').count()) {
    await pg.fill('input[type="email"]', process.env.DP_USER)
    await pg.fill('input[type="password"]', process.env.DP_PASS)
    await pg.click('button[type="submit"]'); await pg.waitForTimeout(4000)
  }
  await pg.goto('http://localhost:5175/reglage/pro', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  const t = () => pg.evaluate(() => document.body.innerText)
  const v = (n, x) => console.log(n.padEnd(28), x ? '✓' : '✗')
  let x = await t()
  v('page chargee', x.includes('Passer Pro'))
  v('4 offres', ['Solo','Vérification','Équipe','Clinique'].every((s) => x.includes(s)))
  v('plan actuel Solo', x.includes('Plan actuel'))
  v('badge populaire', x.includes('Populaire'))
  v('features', x.includes('Membres de l\'équipe') && x.includes('réseaux sociaux'))
  // basculer sur Équipe puis revenir sur Solo (test sans casser le compte)
  const cardBtns = pg.locator('button:has-text("Passer à cette offre"), button:has-text("Choisir cette offre")')
  await cardBtns.nth(1).click(); await pg.waitForTimeout(600)
  x = await t()
  v('modal bascule', x.includes('appliqué immédiatement') || x.includes('Activer'))
  await pg.click('button:has-text("Activer")'); await pg.waitForTimeout(1500)
  x = await t()
  v('plan active', x.includes('activé') && x.includes('vos nouvelles limites'))
  // vérifier côté stockage que le plan a changé
  await pg.goto('http://localhost:5175/reglage/stockage', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  x = await t()
  const newPlan = x.includes('Équipe') && !x.includes('Solo\n')
  v('stockage reflète Équipe', newPlan)
  // revenir à free pour ne pas perturber
  await pg.goto('http://localhost:5175/reglage/pro', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  const back = pg.locator('button:has-text("Passer à cette offre"), button:has-text("Choisir cette offre")')
  await back.nth(0).click(); await pg.waitForTimeout(600)
  await pg.click('button:has-text("Activer")'); await pg.waitForTimeout(1500)
  x = await t()
  v('retour Solo', x.includes('activé'))
  await pg.screenshot({ path: 'shots/pro-final.png', fullPage: true })
  console.log('errors:', JSON.stringify(errs))
  await b.close()
})()
