const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext({ viewport: { width: 1440, height: 860 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  await pg.goto('http://127.0.0.1:5431/login')
  await pg.fill('input[type="email"]', '' + (process.env.DP_USER||'') + '')
  await pg.fill('input[type="password"]', '' + (process.env.DP_PASS||'') + '')
  await pg.click('button[type="submit"]')
  await pg.waitForTimeout(3500)
  await pg.goto('http://127.0.0.1:5431/dossier-patient'); await pg.waitForTimeout(2000)
  // ouvrir le détail du 1er dossier (œil)
  await pg.locator('a[href*="/dossier-patient/dossier/"]').first().click()
  await pg.waitForTimeout(2500)
  console.log('detail:', await pg.evaluate(() => document.body.innerText.includes('PHOTOS') ? 'ok' : 'non'))
  await pg.screenshot({ path: 'shots/dossier-detail.png' })
  // clic photo -> studio?edit=
  const photoLink = pg.locator('a[href*="/studio?edit="]').first()
  if (await photoLink.count()) {
    await photoLink.click(); await pg.waitForTimeout(3000)
    console.log('studio edit:', await pg.evaluate(() => document.body.innerText.match(/\d+ × \d+/)?.[0] || 'fermé'))
    await pg.screenshot({ path: 'shots/dossier-studio.png' })
    await pg.goBack(); await pg.waitForTimeout(2000)
  } else console.log('pas de photo dans ce dossier')
  // retour grille : menu … sur la 1re carte
  await pg.goto('http://127.0.0.1:5431/dossier-patient'); await pg.waitForTimeout(1800)
  await pg.locator('button:has(svg)').last().catch(()=>{})
  const more = pg.locator('button').filter({ has: pg.locator('svg') })
  await pg.locator('svg').nth(0) // noop
  // cliquer le bouton ... de la première carte : chercher via position
  await pg.mouse.click(0,0)
  const menuBtn = pg.locator('div:has(> div > button) button').nth(0)
  // plus simple : chercher les boutons outline contenant FiMoreHorizontal (3e icône d'action de la 1re carte)
  await pg.locator('button').nth(0) // noop
  const cards = pg.locator('button:has-text("Capturer")')
  await cards.first().waitFor()
  // le bouton ... est le bouton après l'oeil : on clique sur tous les boutons outline de la 1re carte (dernier)
  const firstCard = cards.first().locator('xpath=ancestor::div[contains(@class,"chakra")][1]')
  const menu = pg.locator('button:has-text("Capturer")').first().locator('xpath=following::button[2]').first()
  await menu.click(); await pg.waitForTimeout(500)
  console.log('menu:', await pg.evaluate(() => document.body.innerText.includes('Renommer') ? 'ok' : 'non'))
  await pg.screenshot({ path: 'shots/dossier-menu.png' })
  await pg.click('text=Mettre à la corbeille').catch(()=>{})
  console.log('ERRORS:', errs.filter(e => !e.includes('favicon')))
  await b.close()
})().catch(e => console.log('FAIL', e.message))
