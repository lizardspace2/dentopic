const { chromium } = require('playwright')
const U = 'http://localhost:5175'
const step = (s) => console.log('STEP', s)
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext({ viewport: { width: 1500, height: 900 } })).newPage()
  pg.setDefaultTimeout(10000)
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  await pg.addInitScript(() => localStorage.setItem('dentopic.acq.guide', '1'))
  await pg.goto(`${U}/login`)
  await pg.fill('input[type="email"]', process.env.DP_USER)
  await pg.fill('input[type="password"]', process.env.DP_PASS)
  await pg.click('button[type="submit"]'); await pg.waitForTimeout(3000)
  await pg.goto(`${U}/acquisition`); await pg.waitForTimeout(2500)
  step('acq loaded')
  await pg.locator('text=DÉPART').click(); await pg.waitForTimeout(800)
  step('source modal')
  console.log(await pg.locator('body').innerText().then((t) => t.includes('Source') ? 'modal ok' : 'modal?'))
  await pg.screenshot({ path: 'shots/tips-modal.png' })
  // cliquer la tuile FTP
  const ftp = pg.locator('div', { hasText: /^FTP/ }).last()
  await pg.locator('text=/^FTP/').first().click().catch(async () => {
    await pg.locator('div').filter({ hasText: /FTP/ }).nth(1).click()
  })
  await pg.waitForTimeout(700)
  step('ftp modal')
  await pg.screenshot({ path: 'shots/tips-ftp.png' })
  // choisir le device FTP existant ou le bouton Choisir
  const dev = pg.locator('text=/FTP —/').first()
  if (await dev.count()) await dev.click()
  await pg.locator('button:has-text("Choisir")').first().click().catch(() => {})
  await pg.waitForTimeout(400)
  await pg.keyboard.press('Escape')
  step('picked')
  await b.close()
  console.log('ERRS:', JSON.stringify(errs.slice(0, 4)))
})().catch((e) => console.log('FAIL', e.message.split('\n')[0]))
