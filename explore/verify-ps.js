const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext({ viewport: { width: 1440, height: 860 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  await pg.goto('http://127.0.0.1:5431/login')
  await pg.fill('input[type="email"]', '' + (process.env.DP_USER||'') + '')
  await pg.fill('input[type="password"]', '' + (process.env.DP_PASS||'') + '')
  await pg.click('button[type="submit"]')
  await pg.waitForTimeout(3500)
  await pg.goto('http://127.0.0.1:5431/studio'); await pg.waitForTimeout(1200)
  await pg.click('text=Choisir une photo'); await pg.waitForTimeout(1500)
  await pg.fill('input[placeholder*="Rechercher"]', '1793333215997_0000_0002')
  await pg.waitForTimeout(1800)
  await pg.locator('img').first().click()
  await pg.waitForTimeout(2500)
  // onglet Courbes
  await pg.click('text=Courbes'); await pg.waitForTimeout(800)
  await pg.screenshot({ path: 'shots/ps-curves.png' })
  // drag un point : clic au centre de la courbe puis déplace
  const cv = pg.locator('canvas').last() // canvas du panneau courbes
  const box = await cv.boundingBox()
  await pg.mouse.move(box.x + 100, box.y + 90)
  await pg.mouse.down()
  await pg.mouse.move(box.x + 140, box.y + 50, { steps: 4 })
  await pg.mouse.up()
  await pg.waitForTimeout(800)
  await pg.screenshot({ path: 'shots/ps-curve-moved.png' })
  console.log('courbe appliquée — screenshot')
  // onglet Calques : miniatures + select fusion + fx
  await pg.click('text=Calques'); await pg.waitForTimeout(500)
  console.log('fusion select:', await pg.locator('select').count())
  await pg.locator('select').first().selectOption('multiply')
  await pg.waitForTimeout(500)
  await pg.screenshot({ path: 'shots/ps-multiply.png' })
  // baguette : W puis clic sur le ciel
  await pg.keyboard.press('w')
  const main = await pg.locator('canvas').first().boundingBox()
  await pg.mouse.click(main.x + main.width/2, main.y + 80)
  await pg.waitForTimeout(1200)
  console.log('baguette sel:', await pg.evaluate(() => document.body.innerText.includes('Remplir') ? 'non (outil wand)' : '—'))
  await pg.screenshot({ path: 'shots/ps-wand.png' })
  // poignées de transformation
  await pg.keyboard.press('v')
  await pg.click('text=Poignées de transformation'); await pg.waitForTimeout(400)
  await pg.screenshot({ path: 'shots/ps-handles.png' })
  console.log('ERRORS:', errs.filter(e => !e.includes('favicon')))
  await b.close()
})().catch(e => console.log('FAIL', e.message))
