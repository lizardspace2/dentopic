const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext({ viewport: { width: 1400, height: 850 } })).newPage()
  pg.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
  pg.on('console', (m) => m.type() === 'error' && console.log('CONSOLE:', m.text().slice(0, 300)))
  await pg.goto('http://localhost:5175/login')
  await pg.fill('input[type="email"]', process.env.DP_USER)
  await pg.fill('input[type="password"]', process.env.DP_PASS)
  await pg.click('button[type="submit"]')
  await pg.waitForTimeout(3000)
  await pg.goto('http://localhost:5175/studio'); await pg.waitForTimeout(1500)
  await pg.getByText('Fichier', { exact: true }).click()
  await pg.getByText('Ouvrir une photo…', { exact: true }).click()
  await pg.waitForTimeout(1500)
  await pg.locator('img').first().click(); await pg.waitForTimeout(2500)
  console.log('body:', (await pg.locator('body').innerText()).slice(0, 300))
  await b.close()
})().catch((e) => console.log('FAIL', e.message.split('\n')[0]))
