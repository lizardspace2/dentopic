const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome' }).catch(() => chromium.launch())
  const pg = await (await b.newContext({ viewport: { width: 1400, height: 900 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  await pg.goto('https://app-seven-indol-87.vercel.app/login', { waitUntil: 'networkidle', timeout: 30000 }).catch(async () => {
    await pg.goto('https://app-seven-indol-87.vercel.app/', { waitUntil: 'domcontentloaded', timeout: 30000 })
  })
  await pg.waitForTimeout(3000)
  console.log('URL après goto:', pg.url())
  const hasEmail = await pg.locator('input[type="email"]').count()
  console.log('login form?', hasEmail)
  if (hasEmail) {
    await pg.fill('input[type="email"]', process.env.DP_USER)
    await pg.fill('input[type="password"]', process.env.DP_PASS)
    await pg.click('button[type="submit"]')
    await pg.waitForTimeout(5000)
    console.log('URL après login:', pg.url())
  }
  await pg.goto('https://app-seven-indol-87.vercel.app/reglage/membres', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(4000)
  console.log('URL membres:', pg.url())
  const t = await pg.evaluate(() => document.body.innerText)
  console.log('--- CONTENU ---')
  console.log(t.slice(0, 2500))
  await pg.screenshot({ path: 'shots/ref-membres.png', fullPage: true })
  console.log('errors:', errs.slice(0, 5))
  await b.close()
})()
