const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome' }).catch(() => chromium.launch())
  const pg = await (await b.newContext({ viewport: { width: 1400, height: 1000 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  await pg.goto('http://localhost:5175/', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  if (await pg.locator('input[type="email"]').count()) {
    await pg.fill('input[type="email"]', process.env.DP_USER)
    await pg.fill('input[type="password"]', process.env.DP_PASS)
    await pg.click('button[type="submit"]'); await pg.waitForTimeout(4000)
  }
  await pg.goto('http://localhost:5175/reglage/reseaux', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  const t = () => pg.evaluate(() => document.body.innerText)
  const v = (n, x) => console.log(n.padEnd(26), x ? '✓' : '✗')
  await pg.click('button:has-text("Connecter un réseau")'); await pg.waitForTimeout(600)
  let x = await t()
  const ALL = ['Instagram','Facebook','TikTok','LinkedIn','YouTube','Pinterest','X (Twitter)','Threads','Google Business']
  v('9 reseaux proposes', ALL.every((s) => x.includes(s)))
  await pg.click('[aria-label="Choisir Google Business"]')
  await pg.fill('input[placeholder="@votre.cabinet"]', 'cabinet-gmb-e2e')
  await pg.locator('button:has-text("Connecter")').last().click(); await pg.waitForTimeout(1500)
  x = await t()
  v('doctolib connecte', x.includes('@cabinet-gmb-e2e') && x.includes('Google Business'))
  await pg.screenshot({ path: 'shots/reseaux-11.png', fullPage: true })
  // nettoyage
  await pg.click('[aria-label="Déconnecter cabinet-gmb-e2e"]'); await pg.waitForTimeout(500)
  await pg.click('button:has-text("Oui, déconnecter")'); await pg.waitForTimeout(1200)
  x = await t()
  v('nettoye', !x.includes('@cabinet-gmb-e2e'))
  // même liste dans Publication
  await pg.goto('http://localhost:5175/publication', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  await pg.click('button:has-text("Connecter un réseau")'); await pg.waitForTimeout(600)
  x = await t()
  v('publication : 9 reseaux', ALL.every((s) => x.includes(s)))
  console.log('errors:', JSON.stringify(errs))
  await b.close()
})()
