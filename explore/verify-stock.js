const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome' }).catch(() => chromium.launch())
  const pg = await (await b.newContext({ viewport: { width: 1400, height: 1000 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  await pg.goto('http://localhost:5175/', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  if (await pg.locator('input[type="email"]').count()) {
    await pg.fill('input[type="email"]', process.env.DP_USER)
    await pg.fill('input[type="password"]', process.env.DP_PASS)
    await pg.click('button[type="submit"]'); await pg.waitForTimeout(4000)
  }
  await pg.goto('http://localhost:5175/reglage/stockage', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  const x = await pg.evaluate(() => document.body.innerText)
  const v = (n, ok) => console.log(n.padEnd(26), ok ? '✓' : '✗')
  v('page chargee', x.includes('Usage du stockage'))
  v('plan Solo + Gratuit', x.includes('Solo') && x.includes('Gratuit'))
  v('limites affichees', x.includes('Membres') && x.includes('Comptes réseaux sociaux') && x.includes('Dossiers patients'))
  v('usage reel', x.includes('utilisés sur') && x.includes('fichier'))
  v('pourcentage', /% utilisé/.test(x))
  v('repartition mime', x.includes('JPEG') || x.includes('PNG'))
  v('fichiers lourds', x.includes('Fichiers les plus volumineux'))
  v('offres', x.includes('OFFRES DISPONIBLES') && x.includes('Plan actuel'))
  v('4 plans', ['Solo','Vérification','Équipe','Clinique'].every((s) => x.includes(s)))
  const bar = await pg.locator('[role="progressbar"]').getAttribute('aria-valuenow')
  v('progressbar value', bar !== null && +bar >= 0)
  await pg.screenshot({ path: 'shots/stock-final.png', fullPage: true })
  console.log('errors:', JSON.stringify(errs))
  await b.close()
})()
