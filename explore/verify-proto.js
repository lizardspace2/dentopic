const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome' }).catch(() => chromium.launch())
  const pg = await (await b.newContext({ viewport: { width: 1400, height: 950 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  await pg.goto('http://localhost:5175/', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  if (await pg.locator('input[type="email"]').count()) {
    await pg.fill('input[type="email"]', process.env.DP_USER)
    await pg.fill('input[type="password"]', process.env.DP_PASS)
    await pg.click('button[type="submit"]'); await pg.waitForTimeout(4000)
  }
  await pg.goto('http://localhost:5175/reglage/protocoles', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2000)
  const t = () => pg.evaluate(() => document.body.innerText)
  const v = (n, x) => console.log(n.padEnd(26), x ? '✓' : '✗')
  let x = await t()
  v('page chargee', x.includes('Guides de prise de vue'))
  v('protocoles listes', x.includes('Esthétique — 5 vues') && x.includes('Orthodontie — 8 vues'))
  v('etapes affichees', x.includes('Portrait de face'))
  // créer un protocole
  await pg.click('button:has-text("Nouveau protocole")'); await pg.waitForTimeout(500)
  await pg.fill('input[placeholder*="8 vues"]', 'E2E Proto — 2 vues')
  await pg.fill('textarea', 'Protocole de test E2E')
  await pg.click('button:has-text("Enregistrer")'); await pg.waitForTimeout(1200)
  x = await t()
  v('protocole cree', x.includes('E2E Proto — 2 vues'))
  // sélectionner ce protocole puis ajouter une étape
  await pg.click('text=E2E Proto — 2 vues'); await pg.waitForTimeout(500)
  await pg.click('button:has-text("Ajouter une étape")'); await pg.waitForTimeout(500)
  await pg.fill('input[placeholder*="Intra-orale de face"]', 'Vue de profil E2E')
  await pg.selectOption('select[aria-label="Type de photo"]', 'portrait')
  await pg.fill('textarea', 'Profil droit, lèvres fermées')
  await pg.click('button:has-text("Enregistrer")'); await pg.waitForTimeout(1200)
  x = await t()
  v('etape ajoutee', x.includes('Vue de profil E2E') && x.includes('Requis'))
  // modifier l'étape
  await pg.click('[aria-label="Modifier étape Vue de profil E2E"]'); await pg.waitForTimeout(500)
  await pg.fill('input[placeholder*="Intra-orale de face"]', 'Vue de profil E2E v2')
  await pg.click('button:has-text("Enregistrer")'); await pg.waitForTimeout(1200)
  x = await t()
  v('etape modifiee', x.includes('Vue de profil E2E v2'))
  // définir par défaut
  await pg.click('[aria-label="Défaut E2E Proto — 2 vues"]'); await pg.waitForTimeout(1000)
  x = await t()
  v('defaut pose', x.includes('Défaut'))
  // supprimer étape → confirm
  await pg.click('[aria-label="Supprimer étape Vue de profil E2E v2"]'); await pg.waitForTimeout(600)
  x = await t()
  v('popup suppression etape', x.includes("Voulez-vous vraiment supprimer l'étape"))
  await pg.click('button:has-text("Oui, supprimer")'); await pg.waitForTimeout(1200)
  x = await t()
  v('etape supprimee', !x.includes('Vue de profil E2E v2'))
  // supprimer protocole → confirm
  await pg.click('[aria-label="Supprimer E2E Proto — 2 vues"]'); await pg.waitForTimeout(600)
  x = await t()
  v('popup suppression proto', x.includes('Voulez-vous vraiment supprimer'))
  await pg.click('button:has-text("Oui, supprimer")'); await pg.waitForTimeout(1200)
  x = await t()
  v('protocole supprime', !x.includes('E2E Proto — 2 vues'))
  await pg.screenshot({ path: 'shots/proto-final.png', fullPage: true })
  console.log('errors:', JSON.stringify(errs))
  await b.close()
})()
