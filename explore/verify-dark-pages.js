const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext()).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  await pg.goto('http://127.0.0.1:5431/login')
  await pg.evaluate(() => { localStorage.setItem('dentopic.theme','dark'); localStorage.setItem('dentopic.acq.guide','1') })
  await pg.reload()
  await pg.fill('input[type="email"]', '' + (process.env.DP_USER||'') + '')
  await pg.fill('input[type="password"]', '' + (process.env.DP_PASS||'') + '')
  await pg.click('button[type="submit"]')
  await pg.waitForTimeout(3200)
  await pg.screenshot({ path: 'shots/dark-dashboard.png' })
  await pg.goto('http://127.0.0.1:5431/dossier-patient'); await pg.waitForTimeout(1500)
  await pg.screenshot({ path: 'shots/dark-dossiers.png' })
  await pg.goto('http://127.0.0.1:5431/acquisition'); await pg.waitForTimeout(1500)
  await pg.screenshot({ path: 'shots/dark-acq-clean.png' })
  console.log('ERRORS:', errs.filter(e => !e.includes('favicon')))
  await b.close()
})().catch(e => console.log('FAIL', e.message))
