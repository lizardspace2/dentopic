const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome' }).catch(() => chromium.launch())
  const pg = await (await b.newContext({ viewport: { width: 1400, height: 900 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  await pg.goto('https://app-seven-indol-87.vercel.app/login', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(2500)
  await pg.fill('input[type="email"]', process.env.DP_USER)
  await pg.fill('input[type="password"]', process.env.DP_PASS)
  await pg.click('button[type="submit"]'); await pg.waitForTimeout(5000)
  await pg.goto('https://app-seven-indol-87.vercel.app/reglage/membres', { waitUntil: 'domcontentloaded' })
  await pg.waitForTimeout(3000)
  const t = () => pg.evaluate(() => document.body.innerText)
  await pg.click('button:has-text("Créer un compte")'); await pg.waitForTimeout(700)
  const txt = await t()
  console.log('modal prod?', txt.includes('Créer un compte membre'))
  console.log('champs prod?', txt.includes('Nom complet') && txt.includes('Mot de passe provisoire') && txt.includes('Rôle dans le cabinet'))
  console.log('propriétaire protégé?', !(await pg.locator('[aria-label^="Retirer"]').count()))
  await pg.screenshot({ path: 'shots/ref-mem-modal.png' })
  console.log('errors:', errs)
  await b.close()
})()
