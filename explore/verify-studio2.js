const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext({ viewport: { width: 1440, height: 860 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  await pg.goto('http://127.0.0.1:5431/login')
  await pg.fill('input[type="email"]', '' + (process.env.DP_USER||'') + '')
  await pg.fill('input[type="password"]', '' + (process.env.DP_PASS||'') + '')
  await pg.click('button[type="submit"]')
  await pg.waitForTimeout(3500)
  await pg.goto('http://127.0.0.1:5431/studio'); await pg.waitForTimeout(1500)
  await pg.click('text=Choisir une photo'); await pg.waitForTimeout(1500)
  await pg.fill('input[placeholder*="Rechercher"]', '1793333215997_0000_0002')
  await pg.waitForTimeout(2000)
  await pg.locator('img').first().click()
  await pg.waitForTimeout(2500)
  console.log('dims:', await pg.evaluate(() => document.body.innerText.match(/\d+ × \d+/)?.[0]))
  await pg.screenshot({ path: 'shots/studio-real.png' })
  // trait de pinceau rouge
  await pg.keyboard.press('b')
  const box = await pg.locator('canvas').first().boundingBox()
  await pg.mouse.move(box.x + box.width/2 - 150, box.y + box.height/2 - 50)
  await pg.mouse.down()
  for (let i = 0; i < 12; i++) await pg.mouse.move(box.x + box.width/2 - 150 + i*25, box.y + box.height/2 - 50 + Math.sin(i/2)*40, {steps:2})
  await pg.mouse.up()
  await pg.waitForTimeout(300)
  await pg.screenshot({ path: 'shots/studio-real-brush.png' })
  console.log('ERRORS:', errs.filter(e => !e.includes('favicon')))
  await b.close()
})().catch(e => console.log('FAIL', e.message))
