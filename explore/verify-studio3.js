const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const pg = await (await b.newContext({ viewport: { width: 1440, height: 860 } })).newPage()
  const errs = []
  pg.on('pageerror', (e) => errs.push(e.message))
  pg.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  await pg.goto('http://127.0.0.1:5431/login')
  await pg.fill('input[type="email"]', '' + (process.env.DP_USER||'') + '')
  await pg.fill('input[type="password"]', '' + (process.env.DP_PASS||'') + '')
  await pg.click('button[type="submit"]')
  await pg.waitForTimeout(3500)
  await pg.goto('http://127.0.0.1:5431/studio'); await pg.waitForTimeout(1200)
  // Montage
  await pg.click('text=Fichier'); await pg.waitForTimeout(250)
  await pg.click('text=Montage avant / après'); await pg.waitForTimeout(1500)
  await pg.screenshot({ path: 'shots/studio-montage-modal.png' })
  const thumbs = pg.locator('img')
  await thumbs.nth(0).waitFor({ timeout: 8000 })
  await thumbs.nth(0).click()   // AVANT
  await pg.waitForTimeout(300)
  await thumbs.nth(2).click()   // APRÈS
  await pg.waitForTimeout(300)
  await pg.click('text=Créer le montage')
  await pg.waitForTimeout(2500)
  console.log('dims:', await pg.evaluate(() => document.body.innerText.match(/\d+ × \d+/)?.[0]))
  await pg.screenshot({ path: 'shots/studio-montage.png' })
  // sélection : outil M, tracer, remplir
  await pg.keyboard.press('m')
  const box = await pg.locator('canvas').first().boundingBox()
  await pg.mouse.move(box.x + box.width/2 - 200, box.y + box.height/2 - 120)
  await pg.mouse.down()
  await pg.mouse.move(box.x + box.width/2 + 100, box.y + box.height/2 + 80, { steps: 5 })
  await pg.mouse.up()
  await pg.waitForTimeout(400)
  await pg.screenshot({ path: 'shots/studio-sel.png' })
  await pg.click('text=Remplir')
  await pg.waitForTimeout(400)
  await pg.screenshot({ path: 'shots/studio-fill.png' })
  // undo via bouton
  await pg.keyboard.press('Control+z')
  await pg.keyboard.press('Control+d')
  await pg.waitForTimeout(300)
  console.log('ERRORS:', errs.filter(e => !e.includes('favicon')))
  await b.close()
})().catch(e => console.log('FAIL', e.message))
